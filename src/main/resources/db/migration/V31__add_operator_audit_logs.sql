-- 운영자 접속기록 (계약서 §7-2 「감사 기록」, v1.35.1).
--
-- V1~V30 은 이미 배포됐으므로 수정하지 않는다.
--
-- 개인정보 안전성 확보조치 기준 제8조의 접속기록이다. <b>내용은 적지 않는다</b> —
-- 문의 본문이나 대화를 여기 옮기면 접속기록 자체가 또 하나의 개인정보 더미가 된다.
--
-- 사용자를 외래키로 묶지 않는다. 대상 이용자가 탈퇴해도 이 기록은 기간(1년)까지 남아야
-- 하는데(법령상 보관 — 다른 기록과 반대 방향이라 처리방침에 그렇게 적는다), 외래키로
-- 묶으면 그 상태를 만들 수 없다.
create table operator_audit_logs (
    id               bigint       not null generated by default as identity,
    operator_user_id bigint,
    action           varchar(50)  not null,
    target_user_id   bigint,
    target_id        bigint,
    ip               varchar(45),
    created_at       timestamp(6) not null,
    primary key (id)
);

-- 하루 한 번 "1년 지난 것"을 지운다. 그 조회가 유일한 접근 경로다(조회 API 는 없다).
create index idx_operator_audit_logs_created on operator_audit_logs (created_at);
