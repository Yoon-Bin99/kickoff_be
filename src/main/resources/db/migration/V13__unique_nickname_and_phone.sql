-- 대소문자 무시 제약을 왜 안 거는가 (2026-08-31 실측, supervisor 방침 A 확정)
--
-- 계약서 §3(v1.16.0)의 중복 판정은 닉네임·이메일 모두 <b>대소문자 무시</b>다. 그래서
-- 제약도 lower() 기준이어야 맞는데, <b>두 DB 에 같은 SQL 로 걸 방법이 없다.</b>
--
--   create unique index ... (lower(nickname))        H2 문법오류 / PG 정상
--   alter ... generated always as (lower(x)) stored  H2 문법오류 / PG 정상
--   alter ... as (lower(x))                          H2 정상    / PG 문법오류
--
-- 생성 컬럼은 개념은 양쪽 다 되는데 문법이 정반대로 갈린다. 로컬·테스트가 H2 이고
-- Flyway 가 거기서도 도니, H2 에서 깨지는 DDL 을 올리면 <b>운영은 멀쩡한데 개발자
-- 로컬과 H2 테스트가 통째로 안 뜬다.</b>
--
-- 그래서 DB 는 정확 일치까지만 막고, 대소문자만 다른 쌍은 앱 409 가 막는 이중 방어로
-- 둔다. 이건 <b>이메일이 이미 그 모양</b>이다 — V1 의 unique 도 정확 일치이고 앱만
-- 무시 비교를 한다. 새로 생기는 불일치가 아니라 기존 형태를 따르는 것이다.
--
-- 남는 구멍: 동시 요청이 'Kim' 과 'kim' 을 나란히 넣으면 앱 검사를 둘 다 통과할 수 있다.
-- 좁고, 새 중복은 v1.16.0 이후 사실상 안 생긴다. 방언 분기(Java 마이그레이션 또는
-- {vendor} 폴더)가 다른 이유로 어차피 필요해지는 날 다시 본다 — supervisor 백로그.
