-- V1~V12 는 이미 배포됐으므로 수정하지 않는다. 고치면 Flyway 체크섬이 깨져 기동이 막힌다.
-- 이메일 유니크는 V1 부터 있었다 (users.email varchar(100) unique).

-- phone: null 은 유니크 대상에서 빠져야 한다. 소셜 가입자는 전화번호 없이 계정이
-- 만들어지므로 null 이 여럿 생긴다. 표준 SQL 에서 unique 제약의 null 은 서로 다른 값으로
-- 취급되므로 별도 부분 인덱스가 필요 없다 — H2·PostgreSQL 양쪽에서 실제로 확인했다
-- (null 두 건 삽입 성공, 같은 번호 두 건은 거부).
--
-- 앱은 `existsByPhone` 으로 정확 일치 비교를 하고, 형식이 `010-\d{4}-\d{4}` 로 강제돼
-- 있어(SignupRequest) 판정과 제약이 어긋나지 않는다.
alter table users add constraint uk_users_phone unique (phone);

-- nickname: 정확 일치만 막는다 (위 설명 참고). 지금은 DB 제약이 아예 없어서 완전히 같은
-- 문자열도 경합하면 둘 다 들어갈 수 있는데, 그건 이걸로 막힌다.
alter table users add constraint uk_users_nickname unique (nickname);
