-- 채팅 서버로 보낼 이벤트 대기열 (계약서 §10, v1.31.0).
--
-- V1~V22 는 이미 배포됐으므로 수정하지 않는다.
--
-- <b>왜 표가 필요한가.</b> 매칭 취소·탈퇴 같은 일이 일어나면 채팅 서버에 알려야 하는데,
-- 그 자리에서 HTTP 로 부르면 <b>채팅 서버가 꺼져 있을 때 취소·탈퇴가 같이 실패한다.</b>
-- 계약서 §10 이 "채팅 서버의 장애가 BE 동작을 실패시키면 안 된다"고 못박은 지점이다.
-- 그래서 원 트랜잭션 안에서는 여기 한 줄만 넣고(같이 커밋되거나 같이 롤백된다), 보내는
-- 일은 스케줄러가 따로 한다.
--
-- 이벤트 하나가 행 하나다. 행 id 가 곧 계약서의 eventId 이고, 재시도해도 같은 값이 나가
-- 채팅 서버가 멱등하게 처리할 수 있다 — 전달 보장은 "최소 한 번"이다.
--
-- <b>id 목록을 쉼표로 이어 한 칸에 담는다.</b> 자식 표를 두면 전달 단위(= 이벤트 하나)와
-- 저장 단위가 어긋나 읽기도 지우기도 두 배로 번거로워진다. 대신 길이 상한이 생기므로
-- 기록하는 쪽에서 미리 쪼개 여러 행으로 넣는다(ChatOutboxRecorder) — 한 행이 넘치면
-- insert 가 실패하고, 그러면 <b>원 트랜잭션(탈퇴)까지 함께 실패한다.</b> 그 일만은 없어야 한다.
--
-- delivered_at 이 null 인 행이 미전송이다. 따로 상태 칸을 두지 않은 건 "보냈다"와 "보낸
-- 시각"이 같은 사실이라서다 — 둘로 나누면 어긋날 수 있는 자리가 하나 는다.
create table chat_outbox (
    id              bigint        not null generated by default as identity,
    event_type      varchar(30)   not null,
    request_ids     varchar(4000) not null,
    team_ids        varchar(4000) not null,
    attempts        integer       not null,
    next_attempt_at timestamp(6)  not null,
    delivered_at    timestamp(6),
    created_at      timestamp(6)  not null,
    updated_at      timestamp(6)  not null,
    primary key (id),
    -- 이름을 준다. V1 이 이름 없이 만들어 둔 탓에 값 하나를 더하려고 DB 별 자동 명명을
    -- 양쪽 다 지워야 했던 적이 있다 (V16 주석 참고).
    constraint ck_chat_outbox_type check (event_type in ('ROOM_INVALIDATED', 'PURGE'))
);

-- 스케줄러가 5초마다 긁는 조건 그대로다 — 미전송(delivered_at is null) 중 재시도 시각이
-- 지난 것을 오래된 순으로. 7일 지난 완료 행을 지우는 쪽도 같은 인덱스의 앞 칸을 탄다.
create index idx_chat_outbox_pending on chat_outbox (delivered_at, next_attempt_at, id);
