-- 약관·개인정보처리방침 동의 시각 (계약서 §3, v1.21.0).
--
-- V1~V14 는 이미 배포됐거나 배포 대기 중이므로 수정하지 않는다.
--
-- <b>nullable 이다.</b> v1.21.0 이전에 가입한 계정과 소셜 가입자는 이 값이 없다 —
-- 소셜 가입자의 앱 자체 동의 절차는 v1 범위 밖이다 (계약서 §9).
--
-- not null 로 걸려면 기존 행을 어떤 값으로든 채워야 하는데, 그건 <b>받지 않은 동의를
-- 받은 것처럼 기록</b>하는 일이다. 동의 기록은 나중에 분쟁이 났을 때 근거가 되는 값이라
-- 지어내지 않는다. "언제 동의했는지 모른다"는 null 로 남는 게 정직하고, 나중에 기존
-- 사용자에게 재동의를 받는 경로가 생기면 그때 채우면 된다.
--
-- 시각 컬럼은 다른 곳과 같은 timestamp(6) 다. Hibernate 가 OffsetDateTime 을 JVM 기본
-- 시간대(BeApplication 이 Asia/Seoul 로 고정)의 벽시계로 정규화해 넣는다.
alter table users add column terms_agreed_at timestamp(6);
