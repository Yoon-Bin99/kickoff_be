-- 신고 (계약서 §7-2, v1.35.0).
--
-- V1~V28 은 이미 배포됐으므로 수정하지 않는다.
--
-- <b>사용자·팀을 외래키로 묶지 않는다.</b> 신고자나 신고된 쪽이 탈퇴하면 그 식별값만
-- 비우고 신고 건 자체(대상 종류·사유·조치)는 보관 기간까지 남겨야 한다(§7-2 「기록의
-- 보관」). 외래키로 묶으면 그 상태를 만들 수 없다 — 함께 지워지거나 탈퇴가 막힌다.
--
-- target_id 도 마찬가지다. 가리키는 것이 글·리뷰·팀·채팅 메시지로 달라서 외래키를 걸
-- 대상이 하나가 아니고, 대상이 지워진 뒤에도 신고는 남아야 한다 — 그래서 사본을 함께
-- 저장한다(target_title·target_body·target_rating, 그리고 채팅은 아래 표).
create table reports (
    id                bigint       not null generated by default as identity,
    reporter_user_id  bigint,
    reporter_team_id  bigint,
    reported_user_id  bigint,
    target_type       varchar(20)  not null,
    target_id         bigint       not null,
    request_id        bigint,
    reason            varchar(20)  not null,
    rights_holder     varchar(10),
    detail            varchar(500),
    status            varchar(20)  not null,
    auto_hidden       boolean      not null,
    target_title      varchar(200),
    target_body       varchar(2000),
    target_rating     integer,
    resolution_action varchar(20),
    resolution_note   varchar(500),
    resolved_at       timestamp(6),
    created_at        timestamp(6) not null,
    updated_at        timestamp(6) not null,
    primary key (id),
    constraint ck_reports_target_type check (target_type in
        ('POST', 'REVIEW', 'TEAM', 'CHAT_MESSAGE')),
    constraint ck_reports_status check (status in ('OPEN', 'TEMP_HIDDEN', 'CLOSED'))
);

-- 자주 묻는 세 가지: 이 대상에 처리 전 신고가 몇 명인가(자동 가림·운영자 목록),
-- 이 계정이 이미 신고했나(중복·하루 제한), 지금 열려 있는 신고는 무엇인가(운영자 목록).
create index idx_reports_target on reports (target_type, target_id);
create index idx_reports_reporter on reports (reporter_user_id);
create index idx_reports_status on reports (status);

-- 채팅 메시지 신고의 대화 사본 (계약서 §10 report-context).
--
-- 운영자가 볼 때마다 채팅 서버에 다시 묻지 않는다 — 그 사이 대화가 지워질 수도, 채팅
-- 서버가 꺼져 있을 수도 있다. 신고 시점에 신고자에게 보이던 그대로가 증거다.
create table report_chat_messages (
    id             bigint        not null generated by default as identity,
    report_id      bigint        not null,
    message_id     bigint        not null,
    reported       boolean       not null,
    sender_user_id bigint,
    sender_team_id bigint,
    message_type   varchar(10),
    content        varchar(1000) not null,
    sent_at        timestamp(6)  not null,
    primary key (id)
);

create index idx_report_chat_messages_report on report_chat_messages (report_id);
