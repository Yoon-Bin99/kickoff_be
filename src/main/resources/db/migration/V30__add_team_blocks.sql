-- 차단 (계약서 §7-2 「차단」, v1.35.0).
--
-- V1~V29 는 이미 배포됐으므로 수정하지 않는다.
--
-- 계정이 팀을 차단한다. 한 계정이 같은 팀을 두 번 차단할 수는 없고(멱등 — 두 번째
-- 요청은 200 으로 같은 응답을 준다), 외래키로 묶어 사용자나 팀이 사라지면 함께
-- 사라지게 한다. 신고와 달리 <b>남겨 둘 이유가 없는 기록</b>이라서다 — 차단은 그 사람의
-- 화면 설정이지 분쟁 기록이 아니다.
create table team_blocks (
    id              bigint       not null generated by default as identity,
    blocker_user_id bigint       not null,
    blocked_team_id bigint       not null,
    created_at      timestamp(6) not null,
    updated_at      timestamp(6) not null,
    primary key (id),
    constraint uk_team_blocks_user_team unique (blocker_user_id, blocked_team_id),
    constraint fk_team_blocks_blocker foreign key (blocker_user_id) references users,
    constraint fk_team_blocks_team foreign key (blocked_team_id) references teams
);

-- "이 팀을 차단한 사람이 있는가"를 방향을 바꿔 묻는 조회(두 팀 사이 판정)가 있어서
-- 대상 쪽에도 인덱스를 둔다. 반대 방향은 위 unique 가 이미 덮는다.
create index idx_team_blocks_blocked_team on team_blocks (blocked_team_id);
