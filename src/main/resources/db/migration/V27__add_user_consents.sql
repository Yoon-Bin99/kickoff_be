-- 동의 기록 (계약서 §3 「동의」, v1.34.0·v1.34.1).
--
-- V1~V26 은 이미 배포됐으므로 수정하지 않는다.
--
-- <b>왜 표가 필요한가.</b> 전에는 users.terms_agreed_at 한 칸이었다 — "언제 동의했다"만
-- 남고 <b>무엇에 동의했는지</b>는 남지 않았다. 개인정보 보호법 제22조 제1항은 항목을
-- 나누어 받으라고 하고, 제17조의 제3자 제공(연락처)은 성질이 다른 동의라 한 칸에 담을 수 없다.
--
-- 그때 시행 중이던 문서의 시행일을 함께 남기는 것이 핵심이다. "동의했다"만으로는 어느
-- 문서에 동의했는지 증명할 수 없다 — 약관이 개정되면 같은 시각의 동의가 다른 문서를 가리킨다.
--
-- 항목당 한 행이고 다시 동의하면 갱신한다(unique). 이력을 쌓지 않는 것은 의도다 — 판정에는
-- 가장 최근 한 건만 쓰인다. 이력이 필요해지면 unique 를 풀고 행을 쌓는 쪽으로 바꾼다.
create table user_consents (
    id                    bigint      not null generated by default as identity,
    user_id               bigint      not null,
    consent_type          varchar(30) not null,
    agreed_at             timestamp(6) not null,
    document_effective_at timestamp(6) not null,
    created_at            timestamp(6) not null,
    updated_at            timestamp(6) not null,
    primary key (id),
    constraint uk_user_consents_user_type unique (user_id, consent_type),
    constraint ck_user_consents_type check (consent_type in
        ('AGE14', 'TERMS', 'PRIVACY', 'CONTACT_SHARING')),
    constraint fk_user_consents_user foreign key (user_id) references users
);

-- 판정은 언제나 "이 사용자의 모든 동의"를 한 번에 읽는다 (pendingConsents). unique 가
-- user_id 로 시작하므로 그 조회는 이미 인덱스를 탄다 — 따로 만들지 않는다.

-- users.terms_agreed_at 을 지운다.
--
-- 같은 사실을 두 곳에 두면 한쪽만 갱신되는 날이 온다. 이제 진실은 user_consents 이고,
-- 응답의 termsAgreedAt(계약서 §2 — 표시용)은 가입 화면 세 항목의 기록에서 계산한다.
-- 옛 값은 옮기지 않는다: 그 칸은 "세 항목 중 무엇에 동의했는지"를 구별하지 못해서,
-- 옮겨 놓으면 받은 적 없는 동의를 받은 것으로 기록하게 된다. 기존 계정은 다음 로그인에
-- 동의 화면을 한 번 지난다(그것이 이 개편의 목적이다).
alter table users drop column terms_agreed_at;

-- 계좌 공개 확인 시각 (계약서 §5, v1.34.0).
--
-- 작성자가 "이 계좌는 매칭이 수락된 상대 팀 감독에게 보인다"를 확인한 시각이다. 제3자
-- 제공을 알렸다는 기록이라 응답에는 내지 않는다. nullable 인 것이 맞다 — 계좌가 없는 글이
-- 대부분이고, 이 칸이 생기기 전의 글에는 기록이 없다.
alter table match_posts add column payment_share_confirmed_at timestamp(6);
