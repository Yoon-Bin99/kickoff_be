package com.kickoff.be.holiday.dto;

/**
 * 공휴일 목록의 출처 (계약서 §8-2).
 *
 * <b>이 값이 "빈 목록"과 "모른다"를 가른다.</b> 둘 다 {@code holidays: []} 로 나가지만
 * 뜻이 정반대다 — KAKAO 는 "그 해에 공휴일이 없다"(실제로는 있을 수 없으니 사실상
 * 안 나오는 경우)이고, NONE 은 "우리가 알지 못한다"다. FE 는 NONE 일 때 자기 계산값으로
 * 폴백하는데, 둘을 구별하지 못하면 <b>공휴일이 하나도 없는 달력</b>을 그려 놓고 정상이라
 * 믿는다.
 */
public enum HolidaySource {

    /** 카카오 톡캘린더에서 받아 왔다. */
    KAKAO,

    /**
     * 알지 못한다. 세 경우다 — 어드민 키가 없거나, 호출이 실패했거나(타임아웃·오류 응답),
     * 카카오에 그 해 데이터가 없다.
     *
     * 셋을 응답에서 구별하지 않는다. FE 가 할 일은 어느 쪽이든 같고(자기 계산값 사용),
     * 구별해서 알려 주면 어드민 키 상태를 밖에서 떠볼 수 있게 된다.
     */
    NONE
}
