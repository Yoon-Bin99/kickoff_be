package com.kickoff.be.stadium.entity;

/**
 * 구장 정보의 출처 (계약서 §8-1, v1.27.0).
 *
 * 응답에 그대로 나가는 값이다. 화면이 출처를 표기해야 하기 때문인데, 그건 예쁘라고
 * 넣은 게 아니라 <b>공공데이터 이용조건</b>이다 — 서울 공공분은 "서울시 공공서비스예약
 * 제공"을 밝혀야 한다.
 *
 * 출처가 곧 <b>어떤 필드가 채워지는지</b>이기도 하다. 접수 상태·이용 기간은 공공 API 가
 * 주는 값이라 수동 시드에는 없다.
 */
public enum StadiumSource {

    /** 서울 열린데이터광장 체육시설 공공서비스예약 API 동기화분. 접수 상태·이용 기간이 있다. */
    SEOUL_PUBLIC,

    /** 운영자가 직접 넣은 것(경기·인천·사설). v1 은 관리 API 가 없어 시드·SQL 로만 들어온다. */
    MANUAL
}
