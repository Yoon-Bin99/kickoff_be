package com.kickoff.be.chatlink.entity;

/**
 * 채팅 서버로 보내는 이벤트 종류 (계약서 §10).
 *
 * 둘뿐인 이유가 있다. <b>수락은 이벤트가 없고</b>(방은 암묵적으로 존재하고 첫 접근 때
 * RoomContext 로 확인한다), <b>팀 이름·평점 변화도 이벤트가 없다</b>(방 목록은 매번 BE 에서
 * 읽는다). 보내야 하는 것은 채팅 서버가 자기 데이터만 봐서는 알 수 없는 두 가지뿐이다 —
 * 방이 더 이상 유효하지 않게 된 것, 그리고 방 자체가 사라진 것.
 */
public enum ChatEventType {

    /**
     * 그 방의 전제(상태·경기 일시)가 바뀌었다 — 매칭 취소(§6-2), 수락된 신청이 있는 글의
     * matchAt 수정. 채팅 서버는 캐시를 버리고 구독 중인 연결에 ROOM_STATE 를 보낸다.
     * <b>메시지는 지우지 않는다.</b>
     */
    ROOM_INVALIDATED,

    /**
     * 방이 사라졌다 — 회원 탈퇴로 팀이 삭제됐다(§3-4). 채팅 서버는 그 방들의 메시지·나가기
     * 기록을 지운다. 지우는 쪽이라 ROOM_INVALIDATED 와 섞어서는 안 된다.
     */
    PURGE
}
