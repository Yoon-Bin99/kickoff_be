package com.kickoff.be.chatlink.dto;

/**
 * 채팅 서버가 이벤트를 어떻게 받았는지 (계약서 §10 전달 규칙).
 *
 * <b>"2xx 인가"만으로는 모자란다.</b> 기다리면 풀리는 실패(서버가 꺼져 있다)와 기다려도
 * 안 풀리는 실패(본문을 못 읽겠다)가 섞이기 때문이다. 뒤쪽을 계속 재시도하면 그 행 하나가
 * 5초마다 400 을 받아 오면서 영원히 남는다.
 */
public enum ChatEventOutcome {

    /** 2xx. 전달 완료. */
    DELIVERED,

    /**
     * 기다리면 풀릴 수 있는 실패 — 5xx·타임아웃·연결 실패, 그리고 408·429.
     * 지수 백오프로 계속 재시도한다(횟수 제한 없음 — 채팅 서버가 며칠 꺼져 있을 수 있다).
     */
    RETRY,

    /**
     * 401. 공유 비밀이 서로 다르다 — <b>설정 사고지 데이터 문제가 아니다.</b>
     * 값을 맞추면 그대로 풀리므로 재시도는 유지하되, 사람이 알아채야 하므로 경고를 남긴다.
     */
    UNAUTHORIZED,

    /**
     * 그 밖의 4xx — 모르는 type, 깨진 본문 등. <b>같은 것을 다시 보내도 같은 답이 온다.</b>
     * 몇 번 더 시도해 보고 그만둔다(dead).
     */
    REJECTED
}
