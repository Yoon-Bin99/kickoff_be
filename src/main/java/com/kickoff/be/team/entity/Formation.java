package com.kickoff.be.team.entity;

/**
 * 스쿼드 포메이션 (계약서 §1·§4-4, v1.28.0).
 *
 * <b>{@code Team.formation} 과 다른 것이다.</b> 팀 정보의 포메이션은 자유 문자열("4-4-2")로,
 * 팀마다 쓰는 표기가 달라 열거형으로 굳히지 않았다(§4-1). 여기는 스쿼드 보드가 쓰는 값이라
 * 사정이 반대다 — <b>총원 N 이 자리 개수를 정하고 그 개수로 검증</b>해야 하므로 아는 값만
 * 받아야 한다.
 *
 * 이름 규칙: {@code F} + 총원 + 각 줄 인원. <b>앞 숫자가 총원이고 GK 를 포함한다</b>
 * (F11_4_4_2 = 11명, 줄 합 10 + GK 1). 줄 숫자는 수비→미드→공격 순이다.
 *
 * 자리 좌표는 여기 없다. FE 가 포메이션별 고정 테이블을 가진다(§4-4) — 서버는 좌표를 모르고,
 * 알 필요도 없다. 서버가 아는 것은 "몇 자리인가"뿐이다.
 */
public enum Formation {

    F11_4_4_2(11),
    F11_4_3_3(11),
    F11_4_2_3_1(11),
    F11_3_5_2(11),
    F11_3_4_3(11),
    F11_5_3_2(11),
    F7_2_3_1(7),
    F7_3_2_1(7),
    F6_2_2_1(6),
    F6_1_3_1(6);

    private final int totalPlayers;

    Formation(int totalPlayers) {
        this.totalPlayers = totalPlayers;
    }

    /**
     * GK 를 포함한 선발 자리 개수. {@code slots} 가 정확히 이 개수여야 한다 (계약서 §4-4).
     *
     * 줄 숫자에서 계산하지 않고 값으로 들고 있는 이유는 이름이 곧 계약이기 때문이다 —
     * 이름의 앞 숫자와 이 값이 어긋나면 FE·BE 가 서로 다른 개수를 기대하게 된다. 그래서
     * 둘이 일치하는지, 그리고 줄 합 + GK 와도 맞는지를 {@code FormationTest} 가 지킨다.
     * 포메이션을 새로 더할 때 오타 하나로 조용히 틀리는 걸 막는 자리다.
     */
    public int totalPlayers() {
        return totalPlayers;
    }
}
